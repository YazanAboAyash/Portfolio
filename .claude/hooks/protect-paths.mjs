/**
 * Claude Code PreToolUse hook (Edit|Write). Blocks edits to paths the
 * project's hard rules forbid touching. Exit code 2 blocks the tool call and
 * shows the stderr reason to Claude.
 */

import path from "node:path";

let raw = "";
for await (const chunk of process.stdin) raw += chunk;

const filePath = JSON.parse(raw).tool_input?.file_path;
if (typeof filePath !== "string") process.exit(0);

const projectDir = process.env.CLAUDE_PROJECT_DIR ?? process.cwd();
const relPath = path.relative(projectDir, filePath).split(path.sep).join("/");
if (relPath.startsWith("..") || path.isAbsolute(relPath)) process.exit(0);

const baseName = path.basename(relPath);

const rules = [
  {
    blocked: relPath.startsWith("components/ui/"),
    reason:
      "components/ui/ is generated by Shadcn and must not be edited. Wrap or extend the component from a feature folder instead.",
  },
  {
    blocked: relPath === "middleware.ts" || relPath === "middleware.js",
    reason:
      "This project uses proxy.ts as the request hook (Next 16). Never create middleware.ts.",
  },
  {
    blocked: relPath.startsWith("lib/generated/"),
    reason:
      "lib/generated/ is the generated Prisma client. Change prisma/schema.prisma and run `npm run db:generate` instead.",
  },
  {
    blocked: /^\.env(\..+)?$/.test(baseName) && baseName !== ".env.example",
    reason:
      "Env files hold secrets. Ask the user to change them; only .env.example may be edited.",
  },
  {
    blocked: relPath === "package-lock.json",
    reason:
      "Don't hand-edit the lockfile. Change package.json and run `npm install`.",
  },
];

const hit = rules.find((rule) => rule.blocked);
if (hit) {
  console.error(`Blocked edit to ${relPath}: ${hit.reason}`);
  process.exit(2);
}
